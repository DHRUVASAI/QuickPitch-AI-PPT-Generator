import fs from 'node:fs';
import path from 'node:path';
import { verifyQuote, formatVerifiedQuote } from '../core/utils/verify-quote.js';
import { formatMmSs } from '../core/transcript/timestamp-utils.js';

interface TopicQuery {
  term: string;
  lv3Pattern: RegExp;
  captionPattern: RegExp;
}

function main() {
  console.log('='.repeat(90));
  console.log('ITEM 4: TIMELINE COMPARISON - LARGE-V3 VS CAPTION-BASED UNITS');
  console.log('='.repeat(90));

  const lv3Path = path.join(process.cwd(), 'scratch', 'qzAHXO_large_v3_translate.json');
  const step3Path = path.join(process.cwd(), 'scratch', 'qzAHXO_step3_deduped_translated.json');

  const lv3Data = JSON.parse(fs.readFileSync(lv3Path, 'utf-8'));
  const step3Units = JSON.parse(fs.readFileSync(step3Path, 'utf-8'));

  const queries: TopicQuery[] = [
    { term: 'Alexa', lv3Pattern: /\balexa\b/i, captionPattern: /\balexa\b|अलेक्सा/i },
    { term: 'AlphaGo', lv3Pattern: /\balphago\b/i, captionPattern: /\balphago\b|अल्फा\s*गो/i },
    { term: 'Ultron / strong AI', lv3Pattern: /\bultron\b|strong ai/i, captionPattern: /\bultron\b|अल्ट्रॉन|स्ट्रंग\s*एआई|strong ai/i },
    { term: 'Kurzweil / 2045', lv3Pattern: /kurzweil|2045/i, captionPattern: /kurswell|kurzweil|कूर्स|2045|205/i },
    { term: 'Elon Musk', lv3Pattern: /elon musk|musk/i, captionPattern: /elon musk|इलन मस्क|मस्क/i },
    { term: 'Quiz Question', lv3Pattern: /which ai project.*not yet/i, captionPattern: /project does not yet exist|प्रोजेक्ट अभी तक मौजूद नहीं/i },
  ];

  console.log('\n| Topic / Entity       | Whisper Large-v3 Timestamp | Caption-Based Unit Timestamp | Time Delta | Match Excerpt |');
  console.log('|----------------------|----------------------------|------------------------------|------------|---------------|');

  for (const q of queries) {
    // 1. Find in Large-v3 segments
    let lv3Time = 'N/A';
    let lv3Sec = -1;
    let lv3Excerpt = '';
    for (const seg of lv3Data.segments) {
      if (q.lv3Pattern.test(seg.text)) {
        lv3Sec = seg.start;
        lv3Time = `${formatMmSs(seg.start)} (${seg.start.toFixed(1)}s)`;
        lv3Excerpt = seg.text.trim();
        break;
      }
    }

    // 2. Find in Caption-based units
    let capTime = 'N/A';
    let capSec = -1;
    let capExcerpt = '';
    for (const u of step3Units) {
      const matchInEn = q.captionPattern.test(u.translatedText || '');
      const matchInHi = q.captionPattern.test(u.sourceText || '');
      if (matchInEn || matchInHi) {
        capSec = u.startSec;
        capTime = `${formatMmSs(u.startSec)} (${u.startSec.toFixed(1)}s) [Unit ${u.unitIndex}]`;
        capExcerpt = (u.translatedText || '').slice(0, 40);
        break;
      }
    }

    const delta = (lv3Sec >= 0 && capSec >= 0) ? `${Math.abs(lv3Sec - capSec).toFixed(1)}s` : 'N/A';

    console.log(`| ${q.term.padEnd(20)} | ${lv3Time.padEnd(26)} | ${capTime.padEnd(28)} | ${delta.padEnd(10)} | "${(lv3Excerpt || capExcerpt).slice(0, 30)}..." |`);

    // Verify quote in file
    if (lv3Excerpt) {
      const v = verifyQuote(lv3Path, lv3Excerpt.slice(0, 25));
      console.log(`  -> Large-v3 Verification: ${formatVerifiedQuote(v)}`);
    }
  }

  // Explanation of slide ranges
  console.log('\n' + '='.repeat(90));
  console.log('ANALYSIS: WHY PREVIOUS SLIDE RANGES WERE CONTIGUOUS WINDOWS');
  console.log('='.repeat(90));
  console.log(`1. Previous Implementation:
   In previous iterations (Round 3.6 / 3.7), slide chunks were generated by \`buildChunksFromSegments\`,
   which uniformly divided the video duration (327.9s) into N equal, contiguous time windows
   (e.g., Slide 1: 00:00 - 00:49, Slide 2: 00:50 - 01:34, Slide 3: 01:34 - 02:20, etc.).
   This was an artificial geometric split of the timeline that assumed speakers distribute topics
   identically across uniform elapsed minutes.

2. Fixed Grounded Implementation:
   A slide's true source range must be dynamically computed directly from the cited chunks of its bullets:
   source_start = min(citedChunk.startSec across slide bullets)
   source_end = max(citedChunk.endSec across slide bullets)
   This grounds the slide timestamp strictly to the semantic moments referenced in its cards,
   producing precise, non-arbitrary timestamps matching Whisper's actual spoken markers.`);
}

main();
